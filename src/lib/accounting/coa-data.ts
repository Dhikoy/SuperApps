export function groupForCode(code: string): AccountGroup {
  const lead = code.charAt(0);
  if (lead === "1") return "ASSET";
  if (lead === "2") return "LIABILITY";
  if (lead === "3") return "EQUITY";
  if (lead === "4") return "REVENUE";
  return "EXPENSE";
}

export function defaultNormalBalance(group: AccountGroup): NormalBalance {
  return group === "ASSET" || group === "EXPENSE" ? "DEBIT" : "CREDIT";
}

export function isCashCode(code: string): boolean {
  const n = Number(code);
  return n >= 101 && n <= 108;
}

export type CoaSeedRow = {
  code: string;
  name: string;
  group: AccountGroup;
  isHeader: boolean;
  normalBalance: NormalBalance;
  isCash: boolean;
};

export const COA_SEED: CoaSeedRow[] = RAW.map(([code, name]) => {
  const group = groupForCode(code);
  const normal = defaultNormalBalance(group);
  return {
    code,
    name,
    group,
    isHeader: HEADER_CODES.has(code),
    normalBalance: CONTRA_CODES.has(code) ? (normal === "DEBIT" ? "CREDIT" : "DEBIT") : normal,
    isCash: isCashCode(code),
  };
});
